            Route::get('inventory/{item}/movements', [InventoryController::class, 'movements'])->whereNumber('item');
            Route::post('inventory/{item}/movements', [InventoryController::class, 'move'])->whereNumber('item');
            Route::get('inventory/{item}/assignments', [InventoryController::class, 'assignments'])->whereNumber('item');
            Route::post('inventory/{item}/assignments', [InventoryController::class, 'assign'])->whereNumber('item');
            Route::post('inventory/{item}/assignments/{assignment}/return', [InventoryController::class, 'returnAssignment'])->whereNumber('item')->whereNumber('assignment');
